package com.vibes.quantum.server

import kotlinx.serialization.Serializable
import kotlinx.serialization.builtins.ListSerializer
import kotlinx.serialization.json.Json
import java.nio.charset.StandardCharsets
import java.nio.file.AtomicMoveNotSupportedException
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.Paths
import java.nio.file.StandardCopyOption
import java.util.UUID

/** Client-supplied installation metadata. The user identity is ALWAYS taken from the verified session. */
@Serializable
data class UserAppRegistrationRequest(
    val applicationId: String,
    val installationId: String,
    val version: String = "1.0.0"
)

/** One server-issued app identity per account + product + installation. */
@Serializable
data class UserAppInstallationRecord(
    val userId: String,
    val applicationId: String,
    val appId: String,
    val installationId: String,
    val displayName: String,
    val version: String,
    val capabilities: List<String>,
    val status: String,
    val registeredAt: String,
    val lastSeenAt: String
)

@Serializable
data class UserAppInstallationListResponse(val count: Int, val installations: List<UserAppInstallationRecord>)

class UserAppRegistryPersistenceException(cause: Throwable) : RuntimeException(cause)

/**
 * Persistent per-user app-installation registry. appId is generated by the server and is not
 * accepted from the client. Repeated logins from the same installation are idempotent.
 */
internal class UserAppInstallationRegistry(fileName: String?, private val database: VibesDatabase? = null) {
    private val legacyPath: Path? = fileName?.trim()?.takeIf(String::isNotEmpty)?.let { Paths.get(it) }
    private val path: Path? = if (database == null) legacyPath else null
    private val records = linkedMapOf<String, UserAppInstallationRecord>()
    private val json = Json { prettyPrint = true; ignoreUnknownKeys = false }
    val isPersistent: Boolean get() = path != null || database != null

    init { load() }

    @Synchronized
    fun register(userId: String, input: UserAppRegistrationRequest, now: String): Pair<UserAppInstallationRecord, Boolean> {
        val key = key(userId, input.applicationId, input.installationId)
        val previous = records[key]
        val record = UserAppInstallationRecord(
            userId = userId,
            applicationId = input.applicationId,
            appId = previous?.appId ?: "vyronx_${UUID.randomUUID().toString().replace("-", "")}",
            installationId = input.installationId,
            displayName = "Vibes Vyron X",
            version = input.version,
            capabilities = listOf("assistant", "conversation", "memory", "voice", "attachments", "approved-knowledge", "account-installations", "encrypted-private-vault"),
            status = "registered",
            registeredAt = previous?.registeredAt ?: now,
            lastSeenAt = now
        )
        records[key] = record
        try { persist() } catch (failure: UserAppRegistryPersistenceException) {
            if (previous == null) records.remove(key) else records[key] = previous
            throw failure
        }
        return record to (previous == null)
    }

    @Synchronized
    fun snapshot(): List<UserAppInstallationRecord> = records.values.toList()

    @Synchronized
    fun forUser(userId: String): List<UserAppInstallationRecord> =
        records.values.filter { it.userId == userId }.sortedByDescending { it.lastSeenAt }

    private fun key(userId: String, applicationId: String, installationId: String) =
        "$userId\u0000$applicationId\u0000$installationId"

    private fun load() {
        val stored = database?.readDocument("user_app_installations")
        val payload = stored ?: legacyPath?.takeIf { Files.exists(it) }?.let { Files.readString(it, StandardCharsets.UTF_8) } ?: return
        try {
            val loaded = json.decodeFromString(ListSerializer(UserAppInstallationRecord.serializer()), payload)
            loaded.forEach { item ->
                require(item.userId.matches(Regex("usr_[a-f0-9]{32}")))
                require(item.appId.matches(Regex("vyronx_[A-Za-z0-9]{32}")))
                require(item.applicationId == "vibes-vyron-x")
                require(item.installationId.matches(Regex("[A-Za-z0-9][A-Za-z0-9._-]{15,100}")))
                records[key(item.userId, item.applicationId, item.installationId)] = item
            }
            if (stored == null && database != null) database.writeDocument("user_app_installations", json.encodeToString(ListSerializer(UserAppInstallationRecord.serializer()), records.values.toList()))
        } catch (failure: Exception) {
            throw IllegalStateException("Could not load the Vibes user-app registry. Back up and repair the registry file before restarting.", failure)
        }
    }

    private fun persist() {
        val payload = json.encodeToString(ListSerializer(UserAppInstallationRecord.serializer()), records.values.toList())
        if (database != null) {
            try { database.writeDocument("user_app_installations", payload) }
            catch (failure: Exception) { throw UserAppRegistryPersistenceException(failure) }
            return
        }
        val target = path ?: return
        try {
            val absolute = target.toAbsolutePath().normalize()
            val parent = absolute.parent ?: throw IllegalStateException("Registry directory is missing")
            Files.createDirectories(parent)
            val temporary = Files.createTempFile(parent, "vibes-user-apps-", ".tmp")
            try {
                Files.writeString(temporary, payload, StandardCharsets.UTF_8)
                try { Files.move(temporary, absolute, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING) }
                catch (_: AtomicMoveNotSupportedException) { Files.move(temporary, absolute, StandardCopyOption.REPLACE_EXISTING) }
            } finally { Files.deleteIfExists(temporary) }
        } catch (failure: Exception) { throw UserAppRegistryPersistenceException(failure) }
    }
}
